def generate(family: str, name: str, sources_yml: Path) -> tuple[str, Path]:
    if family not in _YAML_TEMPLATES:
        raise SystemExit(f"Unknown family '{family}'. Choose from: sql, files, rest.")

    block = _YAML_TEMPLATES[family].format(name=name, name_upper=name.upper())
    text = sources_yml.read_text() if sources_yml.exists() else "sources: []\n"
    if text.rstrip().endswith("[]"):
        text = text.rstrip()[: -len("[]")] + "\n"
    sources_yml.write_text(text.rstrip("\n") + "\n" + block.lstrip("\n"))

    test_path = TESTS_DIR / f"test_source_{name}.py"
    test_path.write_text(textwrap.dedent(_TEST_TEMPLATES[family]).format(name=name))
    return block, test_path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("family", choices=("sql", "files", "rest"))
    parser.add_argument("name", help="Source name (also the table/resource prefix).")
    parser.add_argument(
        "--sources-yml",
        type=Path,
        default=DEFAULT_SOURCES_YML,
        help="Target sources.yml (default: ingestion/config/sources.yml). Pass a "
        "scratch path to try this without touching the real registry.",
    )
    args = parser.parse_args()

    block, test_path = generate(args.family, args.name, args.sources_yml)
    print(f"Appended to {args.sources_yml}:")
    print(block)
    print(f"Wrote skeleton test: {test_path}")
    print(
        "\nNext: fill in the TODOs above, then:\n"
        "  uv run dhd sources validate\n"
        f"  uv run pytest {test_path}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
